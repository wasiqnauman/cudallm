"""Generate docs/RESULTS.md and docs/img/*.png from results/ (DESIGN.md §15.8).

Every number in the report is read from a results/ file; missing inputs are a hard error.
"""
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from common import REPO_ROOT, RESULTS_DIR  # noqa: E402

DOCS = REPO_ROOT / "docs"
IMG = DOCS / "img"
ABLATION = ["A0_naive", "A1_matvec_opt", "A2_attn_opt", "A3_fused", "A4_graph_nofuse", "A5_full"]
CONTEXTS = [128, 512, 1024, 2048, 4000]
DTYPES = ["bf16", "int8", "int4"]
RPBS = ["1", "2", "4", "8"]
LLAMACPP_TYPES = ["f16", "bf16", "q8_0"]


class MissingInput(RuntimeError):
    pass


def load(rel: str) -> dict:
    path = RESULTS_DIR / rel
    if not path.exists():
        raise MissingInput(f"missing required input: results/{rel}")
    with open(path) as f:
        return json.load(f)


def load_llamacpp(t: str) -> dict | None:
    """llama-bench -o json output: a list of runs; returns the tg256 entry, or None if the run failed."""
    path = RESULTS_DIR / "compare" / f"llamacpp_{t}.json"
    if not path.exists() or path.stat().st_size == 0:
        return None
    try:
        runs = json.loads(path.read_text())
    except json.JSONDecodeError:
        return None
    for r in runs:
        if r.get("n_gen") == 256 and r.get("n_prompt", 0) == 0:
            return r
    return None


def f2(x: float) -> str:
    return f"{x:.2f}"


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def opts_str(d: dict) -> str:
    o = d["options"]
    return f"matvec={o['matvec']} attn={o['attn']} fuse={int(o['fuse'])} graph={int(o['graph'])} rpb={o['rpb']}"


def main() -> None:
    # ---- load everything first so a missing file fails before anything is written ----
    bw = load("bandwidth.json")
    abl = {n: load(f"decode/ablation/{n}.json") for n in ABLATION}
    sweep = load("sweep_matvec.json")
    quant = {d: load(f"decode/quant/Q_{d}.json") for d in DTYPES}
    tg = {d: load(f"decode/tg/tg_{d}.json") for d in DTYPES}
    ctx_opt = {c: load(f"decode/context/ctx_opt_{c}.json") for c in CONTEXTS}
    ctx_naive = {c: load(f"decode/context/ctx_naiveattn_{c}.json") for c in CONTEXTS}
    ppl = {d: load(f"ppl/engine_{d}.json") for d in DTYPES}
    ppl_hf = load("ppl/hf_bf16.json")
    hf = load("compare/hf_bf16.json")
    hf_tg = load("compare/hf_bf16_tg.json")
    llama = {t: load_llamacpp(t) for t in LLAMACPP_TYPES}
    commit_path = RESULTS_DIR / "compare" / "llamacpp_commit.txt"
    if not commit_path.exists():
        raise MissingInput("missing required input: results/compare/llamacpp_commit.txt")
    llama_commit = commit_path.read_text().strip()
    llama_fp = {t: llama[t] for t in ("f16", "bf16") if llama[t] is not None}
    if not llama_fp:
        raise MissingInput("no usable llama.cpp f16/bf16 tg256 result in results/compare/llamacpp_{f16,bf16}.json")
    if llama["q8_0"] is None:
        raise MissingInput("no usable llama.cpp q8_0 tg256 result in results/compare/llamacpp_q8_0.json")

    peak = bw["read_gbps_best"]
    a5 = abl["A5_full"]
    roofline = peak * 1e9 / a5["weight_bytes"]
    best_llama_type = max(llama_fp, key=lambda t: llama_fp[t]["avg_ts"])
    best_llama = llama_fp[best_llama_type]["avg_ts"]

    md: list[str] = ["# cudallm — Results", "",
                     "_Generated by `bench/make_report.py` from the files in `results/`. Do not edit by hand._", ""]

    # 1. Headline
    md += ["## 1. Headline", "", table(
        ["Metric", "Value", "Source"],
        [["cudallm bf16 decode (A5, prompt 128, gen 256)", f"{f2(a5['decode_tok_s_median'])} tok/s",
          "decode/ablation/A5_full.json"],
         ["cudallm bf16 % of measured peak DRAM bandwidth", f"{f2(a5['pct_of_peak'])} %", "decode/ablation/A5_full.json"],
         ["cudallm int4 decode (prompt 128, gen 256)", f"{f2(quant['int4']['decode_tok_s_median'])} tok/s",
          "decode/quant/Q_int4.json"],
         ["HF transformers bf16 (sdpa, eager, prompt 128)", f"{f2(hf['decode_tok_s_median'])} tok/s", "compare/hf_bf16.json"],
         [f"llama.cpp best of f16/bf16 (tg256, {best_llama_type})", f"{f2(best_llama)} tok/s",
          f"compare/llamacpp_{best_llama_type}.json"],
         ["Speedup cudallm A5 vs HF (prompt 128)", f"{f2(a5['decode_tok_s_median'] / hf['decode_tok_s_median'])}x", "—"],
         ["Speedup cudallm bf16 vs llama.cpp best f16/bf16 (tg256)",
          f"{f2(tg['bf16']['decode_tok_s_median'] / best_llama)}x", "decode/tg/tg_bf16.json"],
         ["Speedup cudallm int4 vs cudallm bf16 (A5 options)",
          f"{f2(quant['int4']['decode_tok_s_median'] / quant['bf16']['decode_tok_s_median'])}x", "decode/quant/"]]), ""]

    # 2. Hardware & peak
    md += ["## 2. Hardware & peak", "", table(
        ["Quantity", "Value"],
        [["GPU", bw["gpu_name"]],
         ["read GB/s (best / median)", f"{f2(bw['read_gbps_best'])} / {f2(bw['read_gbps_median'])}"],
         ["write GB/s (best / median)", f"{f2(bw['write_gbps_best'])} / {f2(bw['write_gbps_median'])}"],
         ["copy GB/s, read+write (best / median)", f"{f2(bw['copy_gbps_best'])} / {f2(bw['copy_gbps_median'])}"],
         ["cudaMemcpy D2D GB/s, read+write (best)", f2(bw["memcpy_d2d_gbps_best"])],
         ["Measured peak (read_gbps_best)", f"{f2(peak)} GB/s"],
         ["bf16 weight bytes per decode step", f"{a5['weight_bytes']}"],
         ["Roofline decode rate = peak / weight bytes", f"{f2(roofline)} tok/s"]]),
           "", "Source: results/bandwidth.json, results/decode/ablation/A5_full.json.", ""]

    # 3. Ablation
    rows = []
    a0 = abl["A0_naive"]["decode_tok_s_median"]
    prev = None
    for n in ABLATION:
        d = abl[n]
        t = d["decode_tok_s_median"]
        rows.append([n, opts_str(d), f2(t), f"{d['ms_per_token_median']:.3f}", f2(d["achieved_gbps_median"]),
                     f2(d["pct_of_peak"]), f"{t / a0:.2f}x", "—" if prev is None else f"{t / prev:.3f}x"])
        prev = t
    md += ["## 3. Ablation (bf16, prompt 128, gen 256, median of 5)", "", table(
        ["Run", "Options", "tok/s", "ms/token", "GB/s", "% peak", "vs A0", "vs previous"], rows),
        "", "Source: results/decode/ablation/*.json. ![ablation](img/ablation.png)", ""]

    # 4. Matvec sweep
    rows = []
    for wt in DTYPES:
        win = str(sweep["winners"][wt])
        cells = []
        for r in RPBS:
            v = f2(sweep["weighted_us"][wt][r])
            cells.append(f"**{v}**" if r == win else v)
        rows.append([wt] + cells)
    md += ["## 4. Matvec rows-per-block sweep (weighted µs = 16·(qkv+wo+gate_up+down) + lm_head)", "",
           table(["wtype"] + [f"rpb {r}" for r in RPBS], rows), "", "Winner in bold. Source: results/sweep_matvec.json.", ""]

    # 5. Quantization
    rows = []
    base_ppl = ppl["bf16"]["ppl"]
    for d in DTYPES:
        q = quant[d]
        p = ppl[d]["ppl"]
        rows.append([d, str(q["weight_bytes"]), f2(q["decode_tok_s_median"]), f2(q["pct_of_peak"]), f"{p:.4f}",
                     "—" if d == "bf16" else f"{100 * (p - base_ppl) / base_ppl:+.2f} %"])
    md += ["## 5. Quantization (A5 options, prompt 128, gen 256; WikiText-2 PPL, 40 × 512 tokens)", "",
           table(["dtype", "weight bytes", "tok/s", "% peak", "PPL (engine)", "ΔPPL vs engine bf16"], rows), "",
           f"HF transformers bf16 PPL on the same protocol: {ppl_hf['ppl']:.4f} (results/ppl/hf_bf16.json).",
           "Sources: results/decode/quant/*.json, results/ppl/engine_*.json. ![quant](img/quant.png)", ""]

    # 6. Context scaling
    rows = [[str(c), f2(ctx_opt[c]["decode_tok_s_median"]), f2(ctx_naive[c]["decode_tok_s_median"]),
             f"{ctx_opt[c]['decode_tok_s_median'] / ctx_naive[c]['decode_tok_s_median']:.2f}x"] for c in CONTEXTS]
    md += ["## 6. Context scaling (bf16, fused + graph, gen 32, median of 3)", "",
           table(["prompt length", "opt attention tok/s", "naive attention tok/s", "opt / naive"], rows), "",
           "Source: results/decode/context/*.json. ![context](img/context.png)", ""]

    # 7. Comparison
    rows = [["cudallm", "bf16", "tg256 (prompt 1)", f2(tg["bf16"]["decode_tok_s_median"]), "decode/tg/tg_bf16.json"],
            ["cudallm", "int8", "tg256 (prompt 1)", f2(tg["int8"]["decode_tok_s_median"]), "decode/tg/tg_int8.json"],
            ["cudallm", "int4", "tg256 (prompt 1)", f2(tg["int4"]["decode_tok_s_median"]), "decode/tg/tg_int4.json"],
            ["HF transformers", "bf16", "tg256 (prompt 1)", f2(hf_tg["decode_tok_s_median"]), "compare/hf_bf16_tg.json"]]
    for t in LLAMACPP_TYPES:
        if llama[t] is not None:
            rows.append(["llama.cpp", t, "tg256 (prompt 0)", f2(llama[t]["avg_ts"]), f"compare/llamacpp_{t}.json"])
        else:
            rows.append(["llama.cpp", t, "tg256", "run failed", f"compare/llamacpp_{t}.json"])
    rows += [["cudallm", "bf16", "prompt 128, gen 256", f2(a5["decode_tok_s_median"]), "decode/ablation/A5_full.json"],
             ["HF transformers", "bf16", "prompt 128, gen 256", f2(hf["decode_tok_s_median"]), "compare/hf_bf16.json"]]
    md += ["## 7. Comparison with HF transformers and llama.cpp (same GPU)", "",
           table(["Engine", "Weights", "Benchmark", "tok/s", "Source (results/)"], rows), "",
           f"Versions: transformers {hf['transformers']}, torch {hf['torch']}; llama.cpp commit {llama_commit} "
           "(results/compare/llamacpp_commit.txt).",
           "", "Note: cudallm int8 and llama.cpp q8_0 are not the same format — q8_0 uses one scale per 32-element "
           "block, cudallm int8 one scale per output row — so that pair is an approximate comparison.",
           "", "![compare](img/compare.png)", ""]

    # 8. Provenance
    prov = [("bandwidth.json", bw), ("sweep_matvec.json", sweep), ("compare/hf_bf16.json", hf),
            ("compare/hf_bf16_tg.json", hf_tg), ("ppl/hf_bf16.json", ppl_hf)]
    prov += [(f"decode/ablation/{n}.json", abl[n]) for n in ABLATION]
    prov += [(f"decode/quant/Q_{d}.json", quant[d]) for d in DTYPES]
    prov += [(f"decode/tg/tg_{d}.json", tg[d]) for d in DTYPES]
    prov += [(f"decode/context/ctx_opt_{c}.json", ctx_opt[c]) for c in CONTEXTS]
    prov += [(f"decode/context/ctx_naiveattn_{c}.json", ctx_naive[c]) for c in CONTEXTS]
    prov += [(f"ppl/engine_{d}.json", ppl[d]) for d in DTYPES]
    commits = sorted({d.get("git_commit", "MISSING") for _, d in prov})
    md += ["## 8. Provenance", "",
           f"Distinct git commits across the cudallm/HF result files: {', '.join(commits)}. "
           f"llama.cpp: {llama_commit}.", "", table(["File (results/)", "git_commit"],
                                                    [[p, d.get("git_commit", "MISSING")] for p, d in prov]), ""]

    DOCS.mkdir(exist_ok=True)
    (DOCS / "RESULTS.md").write_text("\n".join(md))
    print(f"wrote {DOCS / 'RESULTS.md'}")

    # ---- plots ----
    IMG.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"figure.facecolor": "white", "axes.facecolor": "white", "savefig.facecolor": "white"})

    fig, ax = plt.subplots(figsize=(8, 4))
    vals = [abl[n]["decode_tok_s_median"] for n in ABLATION]
    ax.barh(ABLATION[::-1], vals[::-1], color="#4C72B0")
    ax.axvline(roofline, color="black", linestyle="--", label=f"roofline {roofline:.1f} tok/s")
    for i, v in enumerate(vals[::-1]):
        ax.text(v, i, f" {v:.1f}", va="center")
    ax.set_xlabel("decode tok/s (bf16, prompt 128, gen 256)")
    ax.set_title("Ablation")
    ax.legend(loc="lower right")
    fig.tight_layout()
    fig.savefig(IMG / "ablation.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(CONTEXTS, [ctx_opt[c]["decode_tok_s_median"] for c in CONTEXTS], marker="o", label="opt attention")
    ax.plot(CONTEXTS, [ctx_naive[c]["decode_tok_s_median"] for c in CONTEXTS], marker="o", label="naive attention")
    ax.set_xlabel("prompt length (tokens)")
    ax.set_ylabel("decode tok/s")
    ax.set_title("Context scaling (bf16, fused + graph)")
    ax.set_ylim(bottom=0)
    ax.legend()
    fig.tight_layout()
    fig.savefig(IMG / "context.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 4))
    qv = [quant[d]["decode_tok_s_median"] for d in DTYPES]
    bars = ax.bar(DTYPES, qv, color=["#4C72B0", "#55A868", "#C44E52"])
    for b, d in zip(bars, DTYPES):
        ax.text(b.get_x() + b.get_width() / 2, b.get_height(), f"PPL {ppl[d]['ppl']:.2f}", ha="center", va="bottom")
    ax.set_ylabel("decode tok/s (A5 options)")
    ax.set_title("Weight-only quantization")
    fig.tight_layout()
    fig.savefig(IMG / "quant.png", dpi=150)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 4))
    groups = ["16-bit weights", "8-bit weights"]
    ours = [tg["bf16"]["decode_tok_s_median"], tg["int8"]["decode_tok_s_median"]]
    hfv = [hf_tg["decode_tok_s_median"], 0.0]
    llv = [best_llama, llama["q8_0"]["avg_ts"]]
    x = range(len(groups))
    w = 0.27
    ax.bar([i - w for i in x], ours, w, label="cudallm")
    ax.bar(list(x), hfv, w, label="HF transformers (bf16 only)")
    ax.bar([i + w for i in x], llv, w, label=f"llama.cpp ({best_llama_type} / q8_0)")
    ax.set_xticks(list(x))
    ax.set_xticklabels(groups)
    ax.set_ylabel("tg256 decode tok/s")
    ax.set_title("Comparison on the same GPU")
    ax.legend()
    fig.tight_layout()
    fig.savefig(IMG / "compare.png", dpi=150)
    plt.close(fig)
    print(f"wrote plots in {IMG}")


if __name__ == "__main__":
    try:
        main()
    except MissingInput as ex:
        print(f"make_report: {ex}", file=sys.stderr)
        sys.exit(1)
